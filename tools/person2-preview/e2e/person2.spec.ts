import { test, expect } from "@playwright/test";
import { FIXTURE_TOKEN } from "../../../lib/client/fixtures";
test.beforeEach(async ({ request }) => { await request.post("/api/preview/reset"); });
test("phone guest follows real HTTP status updates, alerts once, shows stale state and collection", async ({ page, request, context }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  const urls: string[] = []; page.on("request", req => urls.push(req.url()));
  await page.goto(`/guest#token=${FIXTURE_TOKEN}`);
  await expect(page.getByRole("heading", { name: "You're in the queue" })).toBeVisible();
  await page.getByRole("button", { name: "Enable sound alert" }).click();
  await expect(page.getByRole("button", { name: "Turn sound off" })).toBeVisible();
  await request.post("/api/preview/status", { data: { status: "making" } });
  await expect(page.getByRole("heading", { name: "Made just for you" })).toBeVisible({ timeout: 10000 });
  await request.post("/api/preview/status", { data: { status: "ready" } });
  await expect(page.getByRole("heading", { name: "Your drinks are ready!" })).toBeVisible({ timeout: 10000 });
  await expect(page.getByRole("main").getByRole("alert")).toContainText("Ready for collection");
  await context.setOffline(true);
  await expect(page.getByText("Offline · showing last synced data")).toBeVisible();
  await expect(page.getByText("1126-A-001", { exact: true })).toBeVisible();
  await context.setOffline(false);
  await request.post("/api/preview/status", { data: { status: "collected" } });
  await expect(page.getByRole("heading", { name: "Enjoy every sip" })).toBeVisible({ timeout: 10000 });
  expect(urls.filter(url => url.includes("/api/")).some(url => url.includes(FIXTURE_TOKEN))).toBe(false);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
