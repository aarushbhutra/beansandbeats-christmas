test("menu edit survives preview reload pending, syncs once and preserves old report prices", async ({ page, context, request }) => {
  await page.goto("/"); await page.getByRole("button", { name: "Use booth-lead role", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Lead role selected");
  await page.goto("/lead/menu");
  const price = page.getByRole("textbox", { name: "Price for White Christmas Latte" });
  await expect(price).toHaveValue("6.50");
  await context.setOffline(true); await price.fill("7.25");
  await page.locator("form").first().getByRole("button", { name: "Save changes" }).click();
  await expect(page.getByText("Saved on this tablet", { exact: false })).toBeVisible();
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem("p2-preview-fixture-operations")!));
  expect(saved).toHaveLength(1);
  await page.route("**/api/preview/operation", route => route.abort());
  await context.setOffline(false);
  await page.reload();
  await expect(page.getByRole("button", { name: "Pending sync", exact: true })).toBeDisabled();
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem("p2-preview-fixture-operations")!).length)).toBe(1);
  await page.unroute("**/api/preview/operation");
  await expect.poll(async () => (await (await request.get("/api/menu")).json()).items[0].priceCents, { timeout: 10000 }).toBe(725);
  await page.reload(); await expect(price).toHaveValue("7.25");
  await expect(page.getByText("revision 3", { exact: false }).first()).toBeVisible();
  expect((await context.request.post("/api/preview/operation", { data: saved[0] })).status()).toBe(200);
  expect((await (await request.get("/api/menu")).json()).items[0].revision).toBe(3);
  const r = await (await context.request.get("/api/lead/reports?day=2026-11-26")).json(); expect(r.totalCents).toBe(2430);
});
